  LARGE_SHAPE_CHANCE,
  NOVA_BOMB_COLOR,
  NOVA_BOMB_TTL,
  RADII,
  SPEEDS,
  TRIPLE_SHOT_COLOR,
  TRIPLE_SHOT_TTL,
  W,
